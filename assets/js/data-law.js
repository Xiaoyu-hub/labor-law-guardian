/* --------------------------------------------------------------------------
   法条速查：按关键词在法名 / 条号 / 标题 / 正文 / 标签中检索
   -------------------------------------------------------------------------- */
LJ.searchLaw = function (query, limit) {
  var q = (query || '').trim();
  if (!q) return LJ.LAWS.slice(0, limit || 200);
  var terms = q.split(/\s+/).filter(Boolean);
  var hit = LJ.LAWS.filter(function (a) {
    var hay = a.law + ' ' + a.no + ' ' + a.title + ' ' + a.text + ' ' + a.tags.join(' ');
    return terms.every(function (t) { return hay.indexOf(t) >= 0; });
  });
  return hit.slice(0, limit || 200);
};

/* 按「法名 条号」精确取一条，供其他模块引用时展开全文 */
LJ.getArticle = function (ref) {
  for (var i = 0; i < LJ.LAWS.length; i++) {
    if (LJ.LAWS[i].law + ' ' + LJ.LAWS[i].no === ref) return LJ.LAWS[i];
  }
  return null;
};
